interface FeeSeed {
  tuition: number;
  lab?: number;
  exam?: number;
  library?: number;
  development?: number;
  admission?: number;
}

const feeSet = ({ tuition, lab, exam = 6000, library = 3000, development = 8000, admission = 10000 }: FeeSeed): FeeComponent[] => {
  const fees: FeeComponent[] = [
    { label: 'Tuition fee', amount: tuition, kind: 'tuition' },
    { label: 'Admission & registration fee', amount: admission, kind: 'one-time', note: 'Payable once, at admission' },
    { label: 'Examination fee', amount: exam, kind: 'other' },
    { label: 'Library & digital resources', amount: library, kind: 'other' },
    { label: 'Development & student activity fee', amount: development, kind: 'other' },
  ];
  if (lab) fees.splice(2, 0, { label: 'Laboratory fee', amount: lab, kind: 'other' });
  fees.push(
    { label: 'Hostel (twin sharing, with mess)', amount: 115000, kind: 'optional', note: 'Only for hostel residents' },
    { label: 'Transport (city routes)', amount: 24000, kind: 'optional', note: 'Only for bus users; varies by route' },
  );
  return fees;
};

const sems = (rows: string[][]): SemesterSyllabus[] => rows.map((subjects, i) => ({ semester: i + 1, subjects }));

interface Seed {
  slug: string;
  name: string;
  shortName: string;
  level: DegreeLevel;
  discipline: Program['discipline'];
  departmentSlug: string;
  durationYears: number;
  semesters?: number;
  modes?: Program['modes'];
  intake: number;
  eligibilityTag: Program['eligibilityTag'];
  eligibility: string;
  summary: string;
  overview: string;
  objectives: string[];
  outcomes: string[];
  syllabus: string[][];
  fees: FeeSeed;
  careers: string[];
  placementInfo?: string;
  scholarships?: string[];
  faqs?: FAQ[];
  image: ImageAsset;
  featured?: boolean;
}

const make = (s: Seed): Program => ({
  semesters: s.semesters ?? Math.max(1, Math.round(s.durationYears * 2)),
  modes: s.modes ?? ['Full-time'],
  admissionProcedure: admissionSteps[s.level],
  placementInfo:
    s.placementInfo ??
    'Students are supported by the Training & Placement Cell through internships, skill training and campus recruitment drives. Verified placement outcomes are published on the Placements page.',
  scholarships: s.scholarships ?? ['Merit scholarship for top-ranked applicants', 'Need-based fee concession', 'Government scholarships (state & central schemes)'],
  brochureUrl: '/downloads/placeholder.pdf',
  ...s,
  syllabus: sems(s.syllabus),
  fees: feeSet(s.fees),
  faqs: [...(s.faqs ?? []), ...commonFaqs(s.shortName, s.level)],
});

